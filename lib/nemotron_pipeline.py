import queue

import numpy as np
import torch
from transformers import (
    AutoModelForAudioFrameClassification,
    AutoProcessor,
)

from lib.audio_pipeline import AudioPipelineConfig
from lib.segments import SpeakerSegmentEvent, SpeakerSegmentState

MODEL_ID = "nvidia/Nemotron-3-Diarization"
FRAME_S = 0.01
EPS = 1e-3


class NemotronRealTimePipeline:
    def __init__(
        self,
        input_audio_queue: queue.Queue,
        audio_pipeline_config: AudioPipelineConfig,
        output_event_queue: queue.Queue,
    ):
        print("Loading Nemotron...")
        self.model_id = MODEL_ID
        self.sample_rate = audio_pipeline_config.sample_rate
        self.input_audio_queue = input_audio_queue
        self.output_event_queue = output_event_queue
        self.processor = AutoProcessor.from_pretrained(MODEL_ID)
        self.model = AutoModelForAudioFrameClassification.from_pretrained(
            MODEL_ID,
            device_map="auto",
        )
        self.model.eval()
        self.processor.set_streaming_mode("ultra_low_latency")
        print(f"Model ready. Buffer latency: {self.processor.streaming_latency_ms} ms")

    def run_loop(self):
        """Run Loop generated by ChatGPT + Claude."""

        p = self.processor
        buffer = np.empty(0, dtype=np.float32)
        buffer_start = 0  # absolute sample index of buffer[0]
        total = 0  # absolute samples received so far
        mel_frame_idx = None  # None means the first chunk hasn't been sent yet
        speaker_cache = None
        frames_done = 0
        open_segments = {}  # speaker -> start time of a segment still running

        while True:
            block = self.input_audio_queue.get()
            buffer = np.concatenate((buffer, block))
            total += len(block)

            while True:
                first = mel_frame_idx is None
                if first:
                    start, end = 0, p.num_samples_first_audio_chunk
                else:
                    start = p.audio_chunk_start(mel_frame_idx)
                    end = start + p.num_samples_per_audio_chunk
                if total < end:
                    break  # not enough audio yet

                chunk = buffer[start - buffer_start : end - buffer_start]
                inputs = p(
                    chunk,
                    sampling_rate=self.sample_rate,
                    is_streaming=True,
                    is_first_audio_chunk=first,
                )
                inputs = inputs.to(self.model.device, dtype=self.model.dtype)
                with torch.inference_mode():
                    outputs = self.model(**inputs, speaker_cache=speaker_cache)
                speaker_cache = outputs.speaker_cache

                logits = outputs.logits.cpu()
                self.logits_to_segment_events(logits, frames_done, open_segments)
                frames_done += logits.shape[1]

                step = p.num_mel_frames_per_step
                mel_frame_idx = step if first else mel_frame_idx + step

                next_start = p.audio_chunk_start(
                    mel_frame_idx
                )  # drop audio nobody needs again
                buffer = buffer[next_start - buffer_start :]
                buffer_start = next_start

    def logits_to_segment_events(self, logits, frames_done, open_segments):
        """Converting state into emitted raw events."""
        t0 = frames_done * FRAME_S
        t1 = t0 + logits.shape[1] * FRAME_S
        segs = self.processor.extract_speaker_dict(logits)[0]
        seen = {s["Speaker"] for s in segs}

        for s in segs:
            speaker = s["Speaker"]
            start, end = t0 + s["Start"], t0 + s["End"]  # absolute times

            # the old segment ended before this chunk
            if speaker in open_segments and s["Start"] > EPS:
                self.emit(
                    SpeakerSegmentState.closed, speaker, open_segments.pop(speaker), t0
                )

            if speaker not in open_segments:
                open_segments[speaker] = start
                self.emit(SpeakerSegmentState.open, speaker, start)

            # stopped inside this chunk
            if end < t1 - EPS:
                self.emit(
                    SpeakerSegmentState.closed, speaker, open_segments.pop(speaker), end
                )

        # silent for the whole chunk
        for speaker in [k for k in open_segments if k not in seen]:
            self.emit(
                SpeakerSegmentState.closed, speaker, open_segments.pop(speaker), t0
            )

    def emit(self, state, speaker, start, end=None):
        self.publish_segment_event(SpeakerSegmentEvent(state, speaker, start, end))

    def publish_segment_event(self, event: SpeakerSegmentEvent):
        """Converts events as dictionaries and push to output queue for main process."""
        self.output_event_queue.put(event.as_dict())

    @classmethod
    def start_nemotron(
        cls,
        input_audio_queue: queue.Queue,
        audio_pipeline_config: AudioPipelineConfig,
        output_event_queue: queue.Queue,
    ):
        """Starts Diarization pipeline."""
        NemotronRealTimePipeline(
            input_audio_queue=input_audio_queue,
            audio_pipeline_config=audio_pipeline_config,
            output_event_queue=output_event_queue,
        ).run_loop()
